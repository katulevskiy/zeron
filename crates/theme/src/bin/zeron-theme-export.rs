use std::fs;
use std::path::PathBuf;

use anyhow::{Context as _, Result, bail};
use clap::Parser;
use zeron_theme::artifact::{BrowserTokens, ThemeArtifact};
use zeron_theme::builtin_registry;

const MODULE: &str = "// DO NOT EDIT — generated by zeron-theme-export (cargo run -p zeron-theme --bin zeron-theme-export)\nimport type { ThemeArtifact } from \"../types\";\nimport json from \"./artifact.json\";\n\n/** The whole theme artifact, typed. */\nexport const themeArtifact = json as unknown as ThemeArtifact;\n";

/// Export upstream builtin themes and explicitly browser-owned tokens.
#[derive(Debug, Parser)]
struct Args {
    /// Verify output byte-for-byte without writing any files.
    #[arg(long)]
    check: bool,
    /// Generated output directory (defaults to the browser theme package).
    #[arg(long)]
    output: Option<PathBuf>,
    /// Authored browser-only tokens, separate from upstream theme colors.
    #[arg(long)]
    browser_tokens: Option<PathBuf>,
}

fn main() -> Result<()> {
    let args = Args::parse();
    // Independent of cwd: pnpm executes inside web/packages/theme.
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let source = args
        .browser_tokens
        .unwrap_or_else(|| root.join("web/packages/theme/src/browser-tokens.json"));
    let output = args
        .output
        .unwrap_or_else(|| root.join("web/packages/theme/src/generated"));
    let browser: BrowserTokens = serde_json::from_str(
        &fs::read_to_string(&source).with_context(|| format!("read {}", source.display()))?,
    )
    .with_context(|| format!("parse {}", source.display()))?;
    let json = ThemeArtifact::build(builtin_registry(), browser).json()?;
    let outputs = [("artifact.json", json.as_str()), ("index.ts", MODULE)];
    if args.check {
        for (name, expected) in outputs {
            let path = output.join(name);
            let actual = fs::read_to_string(&path).with_context(|| {
                format!(
                    "read {}; regenerate with cargo run -p zeron-theme --bin zeron-theme-export",
                    path.display()
                )
            })?;
            if actual != expected {
                bail!(
                    "{} is stale; run cargo run -p zeron-theme --bin zeron-theme-export",
                    path.display()
                );
            }
        }
        println!("theme artifact is fresh");
    } else {
        fs::create_dir_all(&output)?;
        for (name, content) in outputs {
            fs::write(output.join(name), content)?;
        }
        println!("wrote theme artifact to {}", output.display());
    }
    Ok(())
}
