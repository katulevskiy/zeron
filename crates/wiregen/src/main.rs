//! Generate the supported upstream browser contract from compiled Rust TS derives.
//! Non-migrated browser/fork models live in proto/src/legacy, outside this gate.

use anyhow::{Context, Result, bail};
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
    process::ExitCode,
};
use ts_rs::{Config, TS};

const HEADER: &str = "// DO NOT EDIT — generated from upstream Rust by `cargo run -p wiregen` (check: `-- --check`).\n";
const TS_HEADER: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.";
type Snapshot = BTreeMap<String, Vec<u8>>;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn export(cfg: &Config) -> Result<()> {
    macro_rules! types {
        ($($ty:ty),* $(,)?) => { $(<$ty as TS>::export_all(cfg).context(stringify!($ty))?;)* };
    }
    // Core identity, registry watches, chat creation/configuration and commands.
    // export_all also walks their named dependencies.
    types!(
        zeron_proto::EngineInfo,
        zeron_proto::SidebarPreferencesState,
        zeron_proto::SidebarPreferences,
        zeron_proto::SidebarSection,
        zeron_proto::SidebarPinChange,
        zeron_proto::SidebarSectionChange,
        zeron_proto::WorkspaceScope,
        zeron_proto::Device,
        zeron_proto::Space,
        zeron_proto::Chat,
        zeron_proto::ChatIndicator,
        zeron_proto::Session,
        zeron_proto::SessionStatus,
        zeron_proto::Model,
        zeron_proto::SteeringMode,
        zeron_proto::SlashCommand,
        zeron_proto::RunRequest,
        zeron_proto::AgentEvent,
        zeron_proto::ContextUsage,
        zeron_doc::SessionCommandEntry,
        zeron_doc::SessionCommandKind,
        zeron_doc::SessionCommandStatus,
        zeron_doc::SessionCommandPayload,
        zeron_doc::SessionMessageEntry,
        zeron_doc::SessionTail,
        zeron_doc::TranscriptUpdate,
        zeron_doc::TranscriptFrame,
        zeron_doc::QueuedMessage,
        zeron_update::UpdateStatus,
    );
    Ok(())
}

/// Inventory the real RPC constants via Rust's AST, never browser string copies.
/// Constants alone do not prove dispatch: the real-engine tests exercise the core.
fn methods(source: &str) -> Result<BTreeMap<String, String>> {
    let file = syn::parse_file(source).context("parse upstream RPC source")?;
    let module = file
        .items
        .iter()
        .find_map(|item| match item {
            syn::Item::Mod(module) if module.ident == "methods" => Some(module),
            _ => None,
        })
        .context("RPC methods module is missing")?;
    let (_, items) = module
        .content
        .as_ref()
        .context("methods must be an inline module")?;
    let mut methods = BTreeMap::new();
    for item in items {
        let syn::Item::Const(item) = item else {
            continue;
        };
        let syn::Expr::Lit(expr) = item.expr.as_ref() else {
            bail!(
                "RPC method {} is no longer a literal; update the inventory generator",
                item.ident
            );
        };
        let syn::Lit::Str(value) = &expr.lit else {
            bail!("RPC method {} is not a string", item.ident);
        };
        methods.insert(item.ident.to_string(), value.value());
    }
    Ok(methods)
}

fn method_inventory(source: &str) -> Result<String> {
    let methods = methods(source)?;
    let mut out = HEADER.to_owned();
    out.push_str("\n/** Declared by crates/rpc/src/lib.rs; advanced behavior is not implied. */\nexport const UPSTREAM_METHODS = {\n");
    for (name, value) in &methods {
        out.push_str(&format!("  {name}: {value:?},\n"));
    }
    out.push_str("} as const;\n\nexport type UpstreamMethod = (typeof UPSTREAM_METHODS)[keyof typeof UPSTREAM_METHODS];\n");
    out.push_str("\n/** Required core calls exercised against the engine, not advanced feature claims. */\nexport const CORE_METHODS = [\n");
    for name in [
        "ENGINE_INFO",
        "LOCAL_DEVICE",
        "WATCH_DEVICES",
        "WATCH_SPACES",
        "WATCH_CHATS",
        "WATCH_SESSIONS",
        "MUTATE",
        "QUEUE_COMMAND",
        "WATCH_DOC_MESSAGES",
        "WATCH_QUEUE",
        "LIST_HARNESSES",
        "LIST_MODELS",
    ] {
        if !methods.contains_key(name) {
            bail!("required upstream core method {name} is missing");
        }
        out.push_str(&format!("  UPSTREAM_METHODS.{name},\n"));
    }
    out.push_str("] as const;\n\n/** Retired fork-only calls, retained for negative contract checks, not supported upstream. */\nexport const UNSUPPORTED_LEGACY_METHODS = [\n  \"PrepareSpacePath\",\n  \"SetSidebarPins\",\n  \"SetSidebarSections\",\n  \"WatchSidebarState\",\n] as const;\n");
    Ok(out)
}

