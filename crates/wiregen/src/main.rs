fn snapshot(dir: &Path) -> Result<Snapshot> {
    let mut files = Snapshot::new();
    if !dir.exists() {
        return Ok(files);
    }
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if !path.is_file() {
            bail!(
                "unexpected directory in generated output: {}",
                path.display()
            );
        }
        let name = path
            .file_name()
            .context("missing file name")?
            .to_str()
            .context("non-UTF8 file name")?
            .to_owned();
        files.insert(name, fs::read(path)?);
    }
    Ok(files)
}

fn generate(dir: &Path, rpc_source: &str) -> Result<Snapshot> {
    let cfg = Config::new()
        .with_out_dir(dir)
        .with_large_int("number")
        .with_import_extension(None::<String>);
    export(&cfg)?;
    let mut files = Snapshot::new();
    for (name, bytes) in snapshot(dir)? {
        let text = String::from_utf8(bytes)?;
        let body = text
            .strip_prefix(TS_HEADER)
            .context("unexpected ts-rs output header")?
            .trim_start_matches(['\r', '\n']);
        let body: String = body
            .lines()
            .map(|line| format!("{}\n", line.trim_end()))
            .collect();
        files.insert(name, format!("{HEADER}\n{body}").into_bytes());
    }
    files.insert("constants.ts".into(), constants().into_bytes());
    files.insert(
        "methods.ts".into(),
        method_inventory(rpc_source)?.into_bytes(),
    );
    let mut index = format!("{HEADER}\n");
    for name in files.keys() {
        index.push_str(&format!(
            "export * from \"./{}\";\n",
            name.trim_end_matches(".ts")
        ));
    }
    files.insert("index.ts".into(), index.into_bytes());
    Ok(files)
}

fn differences(expected: &Snapshot, actual: &Snapshot) -> Vec<String> {
    let mut diffs = Vec::new();
    for (name, bytes) in expected {
        match actual.get(name) {
            None => diffs.push(format!("{name}: missing")),
            Some(other) if other != bytes => diffs.push(format!("{name}: differs")),
            _ => (),
        }
    }
    for name in actual.keys().filter(|name| !expected.contains_key(*name)) {
        diffs.push(format!("{name}: no longer generated"));
    }
    diffs
}

fn run() -> Result<bool> {
    let mut check = false;
    let mut output = root().join("web/packages/proto/src/generated");
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--out-dir" => {
                output = PathBuf::from(args.next().context("--out-dir requires a path")?)
            }
            _ => bail!("usage: wiregen [--check] [--out-dir PATH]"),
        }
    }
    let scratch = root().join("target/wiregen");
    fs::create_dir_all(&scratch)?;
    let temp = tempfile::tempdir_in(scratch)?;
    let rpc = fs::read_to_string(root().join("crates/rpc/src/lib.rs"))?;
    let expected = generate(temp.path(), &rpc)?;
    let actual = snapshot(&output)?;
    let diff = differences(&expected, &actual);
    if check {
        if diff.is_empty() {
            println!("wire contracts are fresh ({} files)", expected.len());
            return Ok(true);
        }
        eprintln!(
            "wire contracts are stale; run `cargo run -p wiregen`:\n  {}",
            diff.join("\n  ")
        );
        return Ok(false);
    }
    // Remove only obsolete outputs bearing this generator's provenance.
    // Handwritten/fork models require an explicit migration, not directory cleanup.
    let obsolete: Vec<_> = actual
        .keys()
        .filter(|name| !expected.contains_key(*name))
        .collect();
    for name in &obsolete {
        if !actual[*name].starts_with(HEADER.as_bytes()) {
            bail!("{name} is not upstream-generated; move it to src/legacy before regenerating");
        }
    }
    for name in obsolete {
        fs::remove_file(output.join(name))?;
    }
    fs::create_dir_all(&output)?;
    for (name, bytes) in &expected {
        fs::write(output.join(name), bytes)?;
    }
    println!(
        "generated {} upstream contract files in {}",
        expected.len(),
        output.display()
    );
    Ok(true)
}

fn main() -> ExitCode {
    match run() {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("wiregen: {error:#}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn method_schema_change_is_visible_and_missing_core_is_rejected() {
        let source = fs::read_to_string(root().join("crates/rpc/src/lib.rs")).unwrap();
        let scratch = root().join("target/wiregen-tests");
        fs::create_dir_all(&scratch).unwrap();
        let temp = tempfile::tempdir_in(scratch).unwrap();
        let original = generate(&temp.path().join("original"), &source).unwrap();
        let changed_source = source.replace("\"QueueCommand\"", "\"QueueCommandChanged\"");
        let changed = generate(&temp.path().join("changed"), &changed_source).unwrap();
        // The same snapshot comparison as --check must fail for this isolated
        // supported upstream method change, then succeed after regeneration.
        assert_eq!(differences(&changed, &original), ["methods.ts: differs"]);
        assert!(differences(&changed, &changed).is_empty());
        let changed = source.replace("pub const QUEUE_COMMAND:", "pub const REMOVED_COMMAND:");
        assert!(
            method_inventory(&changed)
                .unwrap_err()
                .to_string()
                .contains("QUEUE_COMMAND")
        );
    }

    #[test]
    fn snapshot_comparison_detects_changed_missing_and_extra_schema_files() {
        let expected = Snapshot::from([("EngineInfo.ts".into(), b"upstream schema".to_vec())]);
        assert!(differences(&expected, &expected).is_empty());
        assert_eq!(
            differences(&expected, &Snapshot::new()),
            ["EngineInfo.ts: missing"]
        );
        let changed = Snapshot::from([("EngineInfo.ts".into(), b"modified schema".to_vec())]);
        assert_eq!(differences(&expected, &changed), ["EngineInfo.ts: differs"]);
        assert!(!differences(&Snapshot::new(), &expected).is_empty());
    }
}
